    #[test]
    fn stackable_range_and_quantity_cap_are_the_original_ones() {
        assert!(!is_stackable(0x0A));
        assert!(is_stackable(0x0B));
        assert!(is_stackable(0x12));
        assert!(!is_stackable(0x13));
        assert!(is_stackable(0x2F));
        assert!(!is_stackable(0x30));
        assert_eq!(ITEM_QUANTITY_CAP, 0xFA);
    }

    #[test]
    fn known_combine_recipes() {
        // Beretta + clip reloads the gun.
        assert_eq!(
            combine(2, 0x0B),
            Some(CombineRecord {
                other_item: 0x0B,
                new_cursor: 0x02,
                new_target: 0x0B,
                effect: 1,
            })
        );
        // Green herb + red herb -> mixed green+red in the cursor slot.
        assert_eq!(
            combine(0x44, 0x43),
            Some(CombineRecord {
                other_item: 0x43,
                new_cursor: 0x46,
                new_target: 0x00,
                effect: 0,
            })
        );
        // Red herb + green herb -> mixed.
        assert_eq!(
            combine(0x43, 0x44).map(|record| (record.new_cursor, record.effect)),
            Some((0x46, 0))
        );
        // The spray has no combine table.
        assert_eq!(combine(0x41, 0x44), None);
        assert!(combine_table(0x80).is_empty());
        assert!(combine_table(200).is_empty());
    }

